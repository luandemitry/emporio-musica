"""Policy retrieval over the store manual.

The manual is small (~14k characters, 28 headings), so the retrieval is lexical:

1. ``data/politicas_da_loja.md`` (generated by ``scripts/ingest_policies.py``) is split
   into one chunk per heading, each labelled with its breadcrumb ("5. Frete > 5.1 ...");
2. chunks are ranked with BM25, counting the heading and the retrieval keywords twice;
3. terms are accent-free, de-pluralised and cut to a 5-letter prefix, a crude stemmer
   that makes "devolver", "devolução" and "devolvo" meet in Portuguese.

No embeddings, no extra API calls, deterministic and easy to test. See the README for
why this is enough here and when it would stop being enough.
"""

from __future__ import annotations

import math
import re
from collections import Counter
from dataclasses import dataclass
from pathlib import Path

from .data import default_data_dir
from .text import tokenize

POLICY_FILE = "politicas_da_loja.md"
PREFIX_LEN = 5
TITLE_WEIGHT = 2  # heading terms are repeated so a heading match outweighs a stray body match
RELATIVE_CUTOFF = 0.4  # drop hits scoring under 40% of the best one
K1, B = 1.5, 0.75  # standard BM25 parameters

_HEADING = re.compile(r"^(#{2,3}) (\d+(?:\.\d+)?)\.? (.+)$")
_KEYWORDS = re.compile(r"^<!-- keywords: (.*) -->$")

# Colloquial words that never appear in the manual -> the manual's vocabulary.
# Applied to queries only, after normalisation and before the prefix cut.
EXPANSIONS = {
    "hora": ["horario"],
    "pagar": ["pagamento"],
    "enviam": ["envio"],
    "enviar": ["envio"],
    "envia": ["envio"],
    "entregam": ["entrega"],
    "abre": ["horario"],
    "aberto": ["horario"],
    "aberta": ["horario"],
    "fecha": ["horario"],
    "fechado": ["horario"],
    "fica": ["endereco"],
    "estorno": ["reembolso"],
    "dinheiro": ["reembolso"],
    "quebrou": ["defeito"],
    "quebrado": ["defeito"],
    "estragou": ["defeito"],
    "estragado": ["defeito"],
}


@dataclass(frozen=True)
class PolicyChunk:
    id: str  # "4.1"
    title: str  # "4. Política de Trocas e Devoluções > 4.1 Direito de Arrependimento"
    text: str
    keywords: str = ""  # retrieval-only synonyms; indexed, never shown to the model


def _terms(text: str, expand: bool = False) -> list[str]:
    tokens = tokenize(text)
    if expand:
        tokens = [x for t in tokens for x in (t, *EXPANSIONS.get(t, ()))]
    return [t[:PREFIX_LEN] for t in tokens]


def chunk_markdown(markdown: str) -> list[PolicyChunk]:
    """One chunk per heading that has body text (headings without text are only breadcrumbs)."""
    chunks: list[PolicyChunk] = []
    section_title = ""
    current: tuple[str, str] | None = None  # (id, breadcrumb)
    body: list[str] = []
    keywords = ""

    def close() -> None:
        text = "\n".join(body).strip()
        if current and text:
            chunks.append(PolicyChunk(current[0], current[1], text, keywords))

    for line in markdown.splitlines():
        match = _HEADING.match(line)
        if not match:
            kw = _KEYWORDS.match(line)
            if kw:
                keywords = kw.group(1)
            elif current:
                body.append(line)
            continue
        close()
        body, keywords = [], ""
        level, number, title = match.groups()
        heading = f"{number}. {title}" if level == "##" else f"{number} {title}"
        if level == "##":
            section_title = heading
            current = (number, heading)
        else:
            current = (number, f"{section_title} > {heading}")
    close()
    return chunks


class PolicyIndex:
    def __init__(self, chunks: list[PolicyChunk]):
        self.chunks = chunks
        self._docs = [Counter(_terms(" ".join([c.title, c.keywords] * TITLE_WEIGHT + [c.text]))) for c in chunks]
        self._lengths = [sum(d.values()) for d in self._docs]
        self._avg_len = sum(self._lengths) / len(self._lengths) if chunks else 0.0
        n = len(chunks)
        df = Counter(term for d in self._docs for term in d)
        self._idf = {t: math.log(1 + (n - c + 0.5) / (c + 0.5)) for t, c in df.items()}

    @classmethod
    def load(cls, path: Path | str | None = None) -> "PolicyIndex":
        file = Path(path) if path else default_data_dir() / POLICY_FILE
        if not file.exists():
            raise FileNotFoundError(
                f"{file} not found. Generate it with: python scripts/ingest_policies.py"
            )
        return cls(chunk_markdown(file.read_text(encoding="utf-8")))

    def search(self, query: str, k: int = 3) -> list[tuple[PolicyChunk, float]]:
        terms = set(_terms(query, expand=True))
        scored = []
        for chunk, doc, length in zip(self.chunks, self._docs, self._lengths):
            score = 0.0
            for t in terms:
                tf = doc.get(t, 0)
                if tf:
                    norm = tf * (K1 + 1) / (tf + K1 * (1 - B + B * length / self._avg_len))
                    score += self._idf[t] * norm
            if score > 0:
                scored.append((chunk, score))
        scored.sort(key=lambda s: -s[1])
        if not scored:
            return []
        best = scored[0][1]
        return [(c, s) for c, s in scored[:k] if s >= RELATIVE_CUTOFF * best]


def consult_policies(index: PolicyIndex, query: str, max_results: int = 3) -> dict:
    """Look up the store's policy manual (hours, payment, returns, shipping, warranty...)."""
    hits = index.search(query, k=max(1, min(int(max_results), 5)))
    if not hits:
        return {
            "results": [],
            "note": (
                "Nothing in the policy manual matches. Do not invent a policy: say you don't "
                "have that information and offer to forward the customer to the team."
            ),
        }
    return {
        "results": [
            {"section": c.id, "title": c.title, "text": c.text, "relevance": round(s, 2)}
            for c, s in hits
        ],
        "note": (
            "Answer only from these texts and quote numbers and deadlines exactly. Results are "
            "ranked by lexical similarity, so ignore any that don't address the question. "
            "Lines marked 'Nota interna' are instructions for you, not for the customer."
        ),
    }
